def _calculate_compliance_metrics(work_orders: list) -> dict:
    total = len(work_orders)
    if total == 0:
        return {
            "loto_compliance": None, "inspection_completion": None,
            "documentation_coverage": None, "manual_reference_coverage": None, "safety_audit_pass_rate": None
        }

    completed = sum(1 for wo in work_orders if str(wo.get("status", "")).upper() in ["COMPLETED", "CLOSED"])
    acknowledged = sum(1 for wo in work_orders if wo.get("acknowledged") is True)
    has_ref = sum(1 for wo in work_orders if wo.get("manual_reference"))

    return {
        "loto_compliance": round((acknowledged / total) * 100, 1),
        "inspection_completion": round((completed / total) * 100, 1),
        "documentation_coverage": round((has_ref / total) * 100, 1),
        "manual_reference_coverage": round((has_ref / total) * 100, 1),
        "safety_audit_pass_rate": None
    }


def _create_progress_bar_drawing(percentage: float, hex_color: str = "#1E3A8A") -> Drawing:
    """Generates a dynamic structural vector progress bar for the PDF layout inline."""
    d = Drawing(140, 14)
    # Background frame track
    d.add(Rect(0, 2, 140, 10, fillColor=colors.HexColor("#E2E8F0"), strokeColor=None, rx=4, ry=4))
    # Filled status indicator
    fill_w = max(0, min(140, (percentage / 100.0) * 140))
    if fill_w > 0:
        d.add(Rect(0, 2, fill_w, 10, fillColor=colors.HexColor(hex_color), strokeColor=None, rx=4, ry=4))
    return d


