class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#475569"))
        
        # Top Header Strip (Page 2 onwards)
        if self._pageNumber > 1:
            self.drawString(54, 755, "INDUSTRIAL MAINTENANCE COMPLIANCE & ACCREDITATION REPORT")
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#94A3B8"))
            self.drawRightString(558, 755, "SYSTEM INTELLIGENCE PLATFORM")
            self.setStrokeColor(colors.HexColor("#CBD5E1"))
            self.setLineWidth(0.75)
            self.line(54, 745, 558, 745)
            
        # Standard Engineering Running Bottom Footer across all document pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.75)
        self.line(54, 48, 558, 48)
        
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        self.drawString(54, 34, "CONFIDENTIAL — Maintenance AI Agent Autogenerated System Log")
        
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#1E3A8A"))
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 34, page_text)
        self.restoreState()


def _clean_markdown(text: str) -> str:
    """Removes markdown characters such as asterisks, hashes, and bullets to provide clean string texts."""
    if not text:
        return ""
    cleaned = re.sub(r'\*\*([^*]+)\*\*', r'\1', text)
    cleaned = re.sub(r'\*([^*]+)\*', r'\1', cleaned)
    cleaned = re.sub(r'#+\s*', '', cleaned)
    return cleaned.strip()


def _parse_date(created_at_str: str) -> str:
    """Parses ISO timestamp safely to return clean YYYY-MM-DD format."""
    if not created_at_str:
        return datetime.now().strftime("%Y-%m-%d")
    try:
        return datetime.fromisoformat(str(created_at_str)).strftime("%Y-%m-%d")
    except ValueError:
        return str(created_at_str).split("T")[0].split(" ")[0]


def _map_work_order_to_report(wo: dict) -> dict:
    priority = (wo.get("priority") or "MEDIUM").upper()
    status_raw = (wo.get("status") or "Open").upper()
    report_status = "Approved" if status_raw in ["COMPLETED", "CLOSED"] else "Ready for Review"
    
    if priority in ["CRITICAL", "HIGH"]:
        report_type = "Failure Investigation Report"
        risk_level = "HIGH"
        health_trend = "Critical"
        savings = "High Downtime Reduction Potential"
    elif priority == "MEDIUM":
        report_type = "Predictive Maintenance Report"
        risk_level = "MEDIUM"
        health_trend = "Monitoring"
        savings = "Moderate Maintenance Impact"
    else:
        report_type = "Preventive Maintenance Summary"
        risk_level = "LOW"
        health_trend = "Healthy"
        savings = "Standard Operational Optimization"

    est_time = wo.get("estimated_time") or "N/A"
    mttr_impact = f"Projected MTTR: {est_time}"
    machine_id = wo.get("machine_id") or "UNKNOWN-ASSET"
    error_code = wo.get("error_code") or "GENERIC-ALERT"
    rec_steps = wo.get("recommended_steps") or []

    summary = (
        f"The Maintenance AI Agent detected error {error_code} on {machine_id}. "
        f"Based on the retrieved maintenance manual, a {priority} priority work order was generated. "
        f"The recommended maintenance actions should be performed to restore normal operation and reduce potential downtime."
    )

    return {
        "id": wo.get("work_order_id"),
        "name": f"{report_type} ({machine_id})",
        "type": report_type,
        "generated_by": "Maintenance AI Agent",
        "date": _parse_date(wo.get("created_at")),
        "machine": machine_id,
        "status": report_status,
        "format": "PDF / XLSX" if risk_level == "HIGH" else "PDF",
        "risk_level": risk_level,
        "health_trend": health_trend,
        "mttr_impact": mttr_impact,
        "savings": savings,
        "summary": summary,
        "findings": wo.get("required_tools") or ["Standard instrumentation deployment checked."],
        "risks": wo.get("required_parts") or ["Potential accelerated component wear parameters."],
        "actions": rec_steps if rec_steps else ["Deploy field team to execute standard validation traces."]
    }


def _calculate_overview_metrics(work_orders: list) -> dict:
    total = len(work_orders)
    if total == 0:
        return {
            "total_reports_generated": 0, "reports_this_month": 0, "assets_covered_percent": None,
            "compliance_score": 100.0, "open_audit_findings": 0, "ai_generated_reports": 0
        }
        
    current_month_str = datetime.now().strftime("%Y-%m")
    reports_this_month = sum(1 for wo in work_orders if _parse_date(wo.get("created_at")).startswith(current_month_str))
    open_findings = sum(1 for wo in work_orders if str(wo.get("status", "")).upper() in ["OPEN", "IN_PROGRESS", "PENDING"])
    completed_orders = sum(1 for wo in work_orders if str(wo.get("status", "")).upper() in ["COMPLETED", "CLOSED"])
    
    return {
        "total_reports_generated": total,
        "reports_this_month": reports_this_month,
        "assets_covered_percent": None,
        "compliance_score": round((completed_orders / total) * 100, 1),
        "open_audit_findings": open_findings,
        "ai_generated_reports": total
    }


def _build_reliability_snapshot(work_orders: list) -> dict:
    if not work_orders:
        return {
            "top_risk_assets": [],
            "most_frequent_failure_code": {"code": "N/A", "description": "No tracked errors", "occurrences": 0},
            "highest_workload_department": {"name": "N/A", "utilization_rate": 0.0, "active_orders": 0},
            "compliance_trend": {"quarter": "Q2-2026", "score": 100.0, "delta": "N/A"},
            "preventive_vs_corrective": {"preventive_percent": 100.0, "corrective_percent": 0.0}
        }

    risk_weights = {"CRITICAL": 3, "HIGH": 3, "MEDIUM": 2, "LOW": 1}
    asset_scores = Counter()
    for wo in work_orders:
        m_id = wo.get("machine_id")
        if m_id:
            prio = str(wo.get("priority", "MEDIUM")).upper()
            asset_scores[m_id] += risk_weights.get(prio, 2)
            
    top_assets = []
    for idx, (m_id, score) in enumerate(asset_scores.most_common(5), start=1):
        risk_str = "high" if score >= 6 else ("med" if score >= 3 else "low")
        top_assets.append({"id": str(idx), "tag": m_id, "risk": risk_str})

    error_codes = [wo.get("error_code") for wo in work_orders if wo.get("error_code")]
    most_common_code = Counter(error_codes).most_common(1)
    frequent_code = {
        "code": most_common_code[0][0] if most_common_code else "None Listed",
        "description": "Active Parameter Threshold Trigger",
        "occurrences": most_common_code[0][1] if most_common_code else 0
    }

    depts = [wo.get("assigned_department") for wo in work_orders if wo.get("assigned_department")]
    dept_counts = Counter(depts).most_common(1)
    
    total_depts_count = len(depts) or 1
    highest_dept_name = dept_counts[0][0] if dept_counts else "General Operations"
    highest_dept_orders = dept_counts[0][1] if dept_counts else 0

    highest_dept = {
        "name": highest_dept_name,
        "utilization_rate": round((highest_dept_orders / total_depts_count) * 100, 1),
        "active_orders": highest_dept_orders
    }

    total_count = len(work_orders)
    completed_orders = sum(1 for wo in work_orders if str(wo.get("status", "")).upper() in ["COMPLETED", "CLOSED"])
    comp_score = round((completed_orders / total_count) * 100, 1) if total_count > 0 else 100.0

    high_prio_count = sum(1 for wo in work_orders if str(wo.get("priority", "")).upper() in ["CRITICAL", "HIGH"])
    corrective_percent = round((high_prio_count / total_count) * 100, 1) if total_count > 0 else 0.0

    return {
        "top_risk_assets": top_assets,
        "most_frequent_failure_code": frequent_code,
        "highest_workload_department": highest_dept,
        "compliance_trend": {"quarter": "Q2-2026", "score": comp_score, "delta": "N/A"},
        "preventive_vs_corrective": {
            "preventive_percent": round(100.0 - corrective_percent, 1), 
            "corrective_percent": corrective_percent
        }
    }


