def _create_status_distribution_chart(work_orders: list) -> Drawing:
    """Builds a vector chart analyzing current ledger deployment ratios."""
    d = Drawing(240, 110)
    statuses = [str(w.get("status", "Open")).capitalize() for w in work_orders]
    counter = Counter(statuses)
    
    pc = Pie()
    pc.x = 10
    pc.y = 10
    pc.width = 90
    pc.height = 90
    pc.sideLabels = 0
    
    data_values = list(counter.values())
    data_labels = list(counter.keys())
    
    pc.data = data_values if data_values else [1]
    pc.labels = [f"{v}" for v in data_values] if data_values else ["0"]
    
    color_palette = [colors.HexColor("#1E3A8A"), colors.HexColor("#3B82F6"), colors.HexColor("#F59E0B"), colors.HexColor("#EF4444")]
    for idx in range(len(data_values)):
        pc.slices[idx].fillColor = color_palette[idx % len(color_palette)]
        pc.slices[idx].strokeColor = colors.white
        pc.slices[idx].strokeWidth = 1
        
    d.add(pc)
    
    # Structural Chart Legend Frame Layout Configuration
    leg = Legend()
    leg.x = 115
    leg.y = 85
    leg.dx = 8
    leg.dy = 8
    leg.fontName = "Helvetica"
    leg.fontSize = 8
    leg.boxAnchor = "nw"
    leg.columnMaximum = 5
    leg.strokeColor = None
    leg.colorNamePairs = [(color_palette[i % len(color_palette)], data_labels[i]) for i in range(len(data_labels))]
    d.add(leg)
    return d


